export type Cell = {x: number; y: number};

/** Zamienia mape znakow na liste zapalonych komorek (wysrodkowana wokol 0,0). */
export const cellsOf = (map: string[], on = '#'): Cell[] => {
  const h = map.length;
  const w = map[0].length;
  const cells: Cell[] = [];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (map[y][x] === on) {
        cells.push({x: x - (w - 1) / 2, y: y - (h - 1) / 2});
      }
    }
  }
  return cells;
};

export const BURST_CELLS = cellsOf(BURST);
